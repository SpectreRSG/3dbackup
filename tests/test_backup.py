def write(path: Path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content, encoding="utf-8", newline="")


def make_windows_home(home: Path):
    roaming = home / "AppData" / "Roaming"
    ps = roaming / "PrusaSlicer"
    write(ps / "PrusaSlicer.ini", "[presets]\nprint = 0.20mm QUALITY\n")
    write(ps / "filament" / "My PETG.ini",
          "# generated by PrusaSlicer\nfirst_layer_temperature = 240\ntemperature = 245\r\n")
    write(ps / "printer" / "MK4 custom.ini", "bed_shape = 0x0,250x0,250x210,0x210\n")
    write(ps / "print" / "Fast.ini", "layer_height = 0.3\n")
    write(ps / "sla_material" / "Grey resin.ini", "exposure_time = 2.5\n")
    write(ps / "cache" / "huge.bin", b"\x00" * 100)          # should be skipped
    write(ps / "PrusaSlicer.log", "log stuff")               # should be skipped

    orca = roaming / "OrcaSlicer"
    write(orca / "OrcaSlicer.conf", json.dumps({"app": {"language": "en"}}))
    write(orca / "user" / "default" / "filament" / "Silk PLA.json",
          json.dumps({"name": "Silk PLA", "nozzle_temperature": ["215"],
                      "filament_type": ["PLA"]}))
    write(orca / "user" / "default" / "filament" / "Silk PLA.info", "sync_info = \n")
    write(orca / "user" / "default" / "machine" / "Ender 3.json",
          json.dumps({"printable_height": "250", "machine_start_gcode": "G28\nG29"}))
    write(orca / "user" / "default" / "process" / "0.2 strong.json",
          json.dumps({"wall_loops": "4"}))
    write(orca / "system" / "BBL" / "huge-vendor.json", "{}")   # factory: skipped
    write(orca / "BambuNetworkEngine.conf", "secret token")     # private: skipped

    cura = roaming / "cura" / "5.8"
    write(cura / "cura.cfg", "[general]\nversion = 7\n")
    write(cura / "machine_instances" / "Creality Ender-3.global.cfg",
          "[general]\nname = Creality Ender-3\n[metadata]\ntype = machine\n")
    write(cura / "quality_changes" / "my_profile.inst.cfg",
          "[general]\nname = my profile\n[values]\ninfill_sparse_density = 25\n")
    write(cura / "materials" / "generic_pla.xml.fdm_material",
          '<?xml version="1.0"?><fdmmaterial xmlns="http://www.ultimaker.com/material">'
          "<metadata><name><brand>Generic</brand><material>PLA</material></name></metadata>"
          '<settings><setting key="print temperature">200</setting></settings></fdmmaterial>')
    write(cura / "plugins" / "SomePlugin" / "plugin.py", "print('hi')")   # skipped
    write(cura / "cura.log", "x")                                         # skipped

    blender = roaming / "Blender Foundation" / "Blender" / "4.2"
    write(blender / "config" / "userpref.blend", b"BLENDER\x00\x01\x02binary")
    write(blender / "scripts" / "addons" / "big_addon.py", "x")           # not included

    chitu = roaming / "CHITUBOX"
    write(chitu / "machine" / "Mars 4.cfg", "exposure = 2\n")
    return home


class ScanAndBackupTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.home = make_windows_home(self.tmp / "home")
        self.scanner = Scanner(os_name="windows", home=self.home)

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_detects_programs_with_settings(self):
        found = {d.app.id for d in self.scanner.detect() if d.has_settings}
        self.assertTrue({"prusaslicer", "orcaslicer", "cura", "blender", "chitubox"} <= found)
        self.assertNotIn("bambustudio", found)

    def test_backup_contains_right_files(self):
        bk = create_backup(self.scanner)
        paths = {(a.id, f.path) for a in bk.apps for f in a.files}
        self.assertIn(("prusaslicer", "filament/My PETG.ini"), paths)
        self.assertIn(("orcaslicer", "user/default/filament/Silk PLA.json"), paths)
        self.assertIn(("cura", "materials/generic_pla.xml.fdm_material"), paths)
        self.assertIn(("blender", "config/userpref.blend"), paths)
        # junk, private and factory files are left out
        for app_id, path in paths:
            self.assertNotIn("cache/", path)
            self.assertNotIn("system/", path)
            self.assertFalse(path.endswith(".log"), path)
            self.assertNotIn("BambuNetworkEngine", path)
            self.assertNotIn("plugins/", path)
            self.assertNotIn("addons", path)

    def test_save_load_round_trip_is_exact(self):
        bk = create_backup(self.scanner)
        out = bk.save(self.tmp / "my-backup")
        self.assertEqual(out.suffix, ".3dbackup")
        loaded = Backup.load(out)
        self.assertEqual(loaded.file_count, bk.file_count)
        for app in loaded.apps:
            for f in app.files:
                self.assertTrue(f.is_intact(), f.path)
                original = Path(app.location) / f.path
                self.assertEqual(f.data(), original.read_bytes(), f.path)
        # binary files are base64, text files stay readable
        blend = next(f for a in loaded.apps for f in a.files if f.path.endswith(".blend"))
        self.assertEqual(blend.encoding, "base64")
        petg = next(f for a in loaded.apps for f in a.files if f.name == "My PETG.ini")
        self.assertEqual(petg.encoding, "text")
        self.assertIn("temperature = 245", out.read_text(encoding="utf-8"))

    def test_restore_to_new_computer(self):
        bk = create_backup(self.scanner)
        saved = bk.save(self.tmp / "b.3dbackup")
        new_home = self.tmp / "newhome"
        new_home.mkdir()
        new_scanner = Scanner(os_name="windows", home=new_home)
        results = restore(Backup.load(saved), new_scanner)
        self.assertEqual(len(results), bk.file_count)
        petg = new_home / "AppData/Roaming/PrusaSlicer/filament/My PETG.ini"
        self.assertEqual(petg.read_bytes(),
                         (self.home / "AppData/Roaming/PrusaSlicer/filament/My PETG.ini").read_bytes())
        self.assertTrue((new_home / "AppData/Roaming/cura/5.8/cura.cfg").exists())

    def test_restore_keeps_old_files(self):
        bk = create_backup(self.scanner)
        target = self.home / "AppData/Roaming/PrusaSlicer/print/Fast.ini"
        target.write_text("layer_height = 0.1\n")
        results = restore(bk, self.scanner, app_indexes={0})
        self.assertEqual(target.read_text(), "layer_height = 0.3\n")
        kept = list(target.parent.glob("Fast.ini.before-restore-*"))
        self.assertEqual(len(kept), 1)
        self.assertEqual(kept[0].read_text(), "layer_height = 0.1\n")
        self.assertTrue(any(s == "already up to date" for _, s in results))

    def test_restore_to_folder_and_cross_os(self):
        bk = create_backup(self.scanner)
        out = self.tmp / "look"
        restore(bk, self.scanner, to_folder=out)
        self.assertTrue((out / "PrusaSlicer" / "filament" / "My PETG.ini").exists())

        mac_home = self.tmp / "machome"
        mac_home.mkdir()
        mac = Scanner(os_name="mac", home=mac_home)
        restore(bk, mac)
        self.assertTrue((mac_home / "Library/Application Support/PrusaSlicer/filament/"
                                    "My PETG.ini").exists())
        self.assertTrue((mac_home / "Library/Application Support/cura/5.8/cura.cfg").exists())

    def test_categories(self):
        bk = create_backup(self.scanner)
        cats = {(a.id, f.path): f.category for a in bk.apps for f in a.files}
        self.assertEqual(cats[("prusaslicer", "filament/My PETG.ini")], CAT_FILAMENT)
        self.assertEqual(cats[("prusaslicer", "printer/MK4 custom.ini")], CAT_PRINTER)
        self.assertEqual(cats[("prusaslicer", "print/Fast.ini")], CAT_PRINT)
        self.assertEqual(cats[("prusaslicer", "sla_material/Grey resin.ini")], CAT_RESIN)
        self.assertEqual(cats[("prusaslicer", "PrusaSlicer.ini")], CAT_APP)
        self.assertEqual(cats[("orcaslicer", "user/default/machine/Ender 3.json")], CAT_PRINTER)
        self.assertEqual(cats[("orcaslicer", "user/default/process/0.2 strong.json")], CAT_PRINT)
        self.assertEqual(cats[("cura", "quality_changes/my_profile.inst.cfg")], CAT_PRINT)
        self.assertEqual(cats[("cura", "materials/generic_pla.xml.fdm_material")], CAT_FILAMENT)
        self.assertEqual(categorize("machine/Mars 4.cfg", KIND_RESIN), CAT_PRINTER)
        self.assertEqual(categorize("user/1/filament/x.json", KIND_FDM), CAT_FILAMENT)


class SafetyTests(unittest.TestCase):
    def test_rejects_paths_that_escape(self):
        base = Path(tempfile.gettempdir())
        for bad in ("../evil.ini", "/etc/passwd", "a/../../b", "C:/Windows/x", "..\\x"):
            with self.assertRaises(BackupError, msg=bad):
                safe_join(base, bad)
        self.assertEqual(safe_join(base, "filament/a.ini"), base / "filament" / "a.ini")

    def test_rejects_non_backup_files(self):
        tmp = Path(tempfile.mkdtemp())
        try:
            (tmp / "x.3dbackup").write_text('{"hello": 1}')
            with self.assertRaises(BackupError):
                Backup.load(tmp / "x.3dbackup")
            (tmp / "y.3dbackup").write_text("not json")
            with self.assertRaises(BackupError):
                Backup.load(tmp / "y.3dbackup")
        finally:
            shutil.rmtree(tmp)


class ParserTests(unittest.TestCase):
    def test_prusa_ini(self):
        rows = parse("x.ini", "# c\nlayer_height = 0.2\nstart_gcode = G28\\nG1\n")
        self.assertEqual(rows, [("layer_height", "0.2"), ("start_gcode", "G28\\nG1")])

    def test_cura_cfg_sections(self):
        rows = parse("x.inst.cfg", "[general]\nname = A\n[values]\ninfill = 20\n")
        self.assertEqual(rows, [("general › name", "A"), ("values › infill", "20")])

    def test_klipper_multiline(self):
        rows = parse("printer.cfg", "[gcode_macro START]\ngcode:\n  G28\n  G1 Z5\n")
        self.assertEqual(rows, [("gcode_macro START › gcode", "G28\nG1 Z5")])

    def test_orca_json(self):
        rows = parse("a.json", '{"nozzle_temperature": ["215", "220"], "x": {"y": true}}')
        self.assertEqual(rows, [("nozzle_temperature", "215, 220"), ("x › y", "yes")])

    def test_cura_xml(self):
        rows = parse("a.xml.fdm_material",
                     '<?xml version="1.0"?><m xmlns="urn:x"><settings>'
                     '<setting key="print temperature">200</setting></settings></m>')
        self.assertEqual(rows, [("settings › setting [print temperature]", "200")])

    def test_broken_file_does_not_crash(self):
        self.assertIsNone(parse("a.json", "{broken"))

    def test_profile_name(self):
        self.assertEqual(profile_name("filament/My PETG.ini"), "My PETG")
        self.assertEqual(profile_name("quality_changes/x.inst.cfg"), "x")


class CliTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.home = make_windows_home(self.tmp / "home")
        self.base = ["--os", "windows", "--home", str(self.home)]

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def run_cli(self, *args):
        buf = io.StringIO()
        with redirect_stdout(buf):
            code = cli.main(self.base + list(args))
        return code, buf.getvalue()

    def test_scan_backup_view_restore(self):
        code, out = self.run_cli("scan")
        self.assertEqual(code, 0)
        self.assertIn("PrusaSlicer", out)
        self.assertIn("OrcaSlicer", out)

        bfile = self.tmp / "out.3dbackup"
        code, out = self.run_cli("backup", "-o", str(bfile))
        self.assertEqual(code, 0, out)
        self.assertTrue(bfile.exists())

        code, out = self.run_cli("view", str(bfile))
        self.assertIn("My PETG", out)
        self.assertIn("Filament / Material", out)

        code, out = self.run_cli("view", str(bfile), "--app", "prusaslicer",
                                 "--show", "filament/My PETG.ini")
        self.assertIn("temperature", out)
        self.assertIn("245", out)

        dest = self.tmp / "restored"
        code, out = self.run_cli("restore", str(bfile), "--to", str(dest), "--yes")
        self.assertEqual(code, 0, out)
        self.assertTrue((dest / "PrusaSlicer" / "filament" / "My PETG.ini").exists())

    def test_only_option(self):
        bfile = self.tmp / "o.3dbackup"
        self.run_cli("backup", "--only", "orcaslicer", "-o", str(bfile))
        self.assertEqual({a.id for a in Backup.load(bfile).apps}, {"orcaslicer"})


if __name__ == "__main__":
    unittest.main()
